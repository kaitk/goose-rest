#!/bin/sh
# Prints a large program in today's form (hand) or design A (short): /health,
# then AREAS areas of MODULES scopes of 10 routes each, 10 * AREAS * MODULES + 1
# routes in all. The first area, /public, opens no middleware; every other is
# behind a check that can fail, as hand60's /v1/reports is. Each scope is a
# function of its own, as a program keeps a module's routes. Four routes in
# ten are GETs, seven take a path parameter.
#
# With ROLES 1, middleware nests as an application's roles do: two scopes in
# three outside /public are behind a role, and their PUT and DELETE routes
# behind a permission besides. Each is an inline function that reads a field
# and can fail, as the area's check does.
#
#   genroutes.sh hand|short   (AREAS 3, MODULES 37, ROLES 0)
#
# The defaults are the 1,111 routes the README measures first.
set -eu
case ${1:-} in hand | short) ;; *) echo "usage: genroutes.sh hand|short" >&2; exit 2 ;; esac

awk -v form="$1" -v nareas="${AREAS:-3}" -v nmods="${MODULES:-37}" -v roles="${ROLES:-0}" '
function call(name, inner) {
    return name "(cx) { " inner " };"
}
BEGIN {
    split("public patient staff manager specialist clinic billing partner report admin " \
          "insurer pharmacy lab school employer registry", areas, " ")
    nnames = split("reservation patient manager company user template specialist diagnosis " \
          "contact-request email visit prescription practitioner person payment report " \
          "receptionist scheduler service-group service-usage sms speciality summary-invoice " \
          "week-template work-hour work-incapacity xroad invoice allergy notification " \
          "clinical import account feature-flag app-notification medication audit", names, " ")
    for (m = 1; m <= nmods; m++)
        mods[m] = names[(m - 1) % nnames + 1] (m > nnames ? "-" int((m - 1) / nnames) + 1 : "")
    # method, pattern, the parameters it reads
    r[1] = "GET||"; r[2] = "POST||"; r[3] = "POST|/search|"
    r[4] = "GET|/:id|id"; r[5] = "PUT|/:id|id"; r[6] = "DELETE|/:id|id"
    r[7] = "POST|/:id/confirm|id"; r[8] = "POST|/:id/notes|id"
    r[9] = "PUT|/:id/notes/:note|id note"; r[10] = "GET|/:id/history|id"

    print "// Generated by genroutes.sh " form ", AREAS " nareas ", MODULES " nmods ", ROLES " roles "."
    print "import std;"
    print "import http from \"github.com/kaitk/goose-http@v0.4.3\";"
    print "import rest from \"../../\";"
    if (form == "short") print "import compact from \"../../spikes/12-compact-routes\";"
    print ""
    print "fn ok(cx) { http::respond(cx.out, 200, \"text/plain\", \"ok\"); }"
    print ""
    print "inline fn checked<F>(cx) {"
    print "    let id, has = rest::header(cx, \"X-Tenant\");"
    print "    guard !has || id == \"acme\" else { rest::fail(cx, 400, \"unknown_tenant\"); }"
    print "    F();"
    print "}"
    if (roles) {
        print ""
        print "inline fn role<F>(cx, name: const u8[:]) {"
        print "    let r, has = rest::header(cx, \"X-Role\");"
        print "    guard !has || r == name else { rest::fail(cx, 403, \"forbidden\"); }"
        print "    F();"
        print "}"
        print ""
        print "inline fn permitted<F>(cx) {"
        print "    let p, has = rest::header(cx, \"X-Permission\");"
        print "    guard !has || p == \"write\" else { rest::fail(cx, 403, \"forbidden\"); }"
        print "    F();"
        print "}"
    }
    print ""
    print "fn handle(cx) {"
    if (form == "hand") {
        print "    rest::routes(cx) { cx =>"
        print "        if rest::on(cx, \"GET\", \"/health\") {"
        print "            ok(cx);"
        for (a = 1; a <= nareas; a++) {
            print "        } else if rest::scope(cx, \"/" areas[a] "\") {"
            if (a == 1) print "            rest::route(cx) { " areas[a] "_area(cx); };"
            else print "            rest::route(cx) { checked(cx) { " areas[a] "_area(cx); }; };"
        }
        print "        } else {"
        print "            rest::otherwise(cx);"
        print "        }"
        print "    };"
    } else {
        print "    compact::routes(cx) { cx =>"
        print "        compact::get(cx, \"/health\") { ok(cx); };"
        for (a = 1; a <= nareas; a++) {
            print "        " (a > 1 ? "} else " : "") "if rest::scope(cx, \"/" areas[a] "\") {"
            if (a == 1) print "            " areas[a] "_area(cx);"
            else print "            checked(cx) { " areas[a] "_area(cx); };"
        }
        print "        }"
        print "    };"
    }
    print "}"
    for (a = 1; a <= nareas; a++) {
        print ""
        print "fn " areas[a] "_area(cx) {"
        for (m = 1; m <= nmods; m++) {
            fn = areas[a] "_" mods[m]; gsub("-", "_", fn)
            printf "    %sif rest::scope(cx, \"/%s\") { %s(cx); }\n", (m > 1 ? "else " : ""), mods[m], fn
        }
        if (form == "hand") print "    else { rest::otherwise(cx); }"
        print "}"
        for (m = 1; m <= nmods; m++) {
            fn = areas[a] "_" mods[m]; gsub("-", "_", fn)
            guarded = roles && a > 1 && m % 3 != 0
            ind = guarded ? "        " : "    "
            print ""
            print "fn " fn "(cx) {"
            if (guarded) print "    role(cx, \"" mods[m] "\") {"
            for (i = 1; i <= 10; i++) {
                split(r[i], f, "|")
                body = ""
                np = split(f[3], ps, " ")
                for (p = 1; p <= np; p++)
                    body = body (ps[p] == "id" ? "rest::param_int(cx, \"id\"); " : "rest::param(cx, \"" ps[p] "\"); ")
                body = body "ok(cx);"
                if (guarded && (i == 5 || i == 6)) body = call("permitted", body)
                if (form == "hand")
                    printf "%s%sif rest::on(cx, \"%s\", \"%s\") { %s }\n", ind, (i > 1 ? "else " : ""), f[1], f[2], body
                else
                    printf "%scompact::%s(cx, \"%s\") { %s };\n", ind, tolower(f[1]), f[2], body
            }
            if (form == "hand") print ind "else { rest::otherwise(cx); }"
            if (guarded) print "    };"
            print "}"
        }
    }
    print ""
    print "thread_fn worker(cfg: http::Config) {"
    print "    let e = rest::serve_epoll(cfg) { cx => handle(cx) };"
    print "    guard e.code != 0 else { return; }"
    print "    http::report(e);"
    print "    exit(1);"
    print "}"
    print ""
    print "fn main() {"
    print "    let argv = args();"
    print "    guard argv.len >= 2 && argv[1] == \"http\" else {"
    print "        write_stderr(\"usage: routes http [port]\\n\");"
    print "        exit(2);"
    print "    }"
    print "    var cfg = http::Config { workers: 1, .. };"
    print "    if argv.len > 2 {"
    print "        let p, ok = parse_int(argv[2]);"
    print "        guard ok && p > 0 && p < 65536 else { write_stderr(\"bad port\\n\"); exit(2); }"
    print "        cfg.port = p as i32;"
    print "    }"
    print "    http::exit_on_error(http::stop_on_signals());"
    print "    http::run(cfg, worker);"
    print "}"
}'
